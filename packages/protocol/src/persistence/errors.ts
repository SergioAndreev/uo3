/** Коды ошибок персистентности (P08) с HTTP-статусами для API. */
export const PERSIST_ERRORS = {
  PERSIST_ENTITY_ID_COLLISION: 409,
  PERSIST_VERSION_CONFLICT: 409,
  PERSIST_OWNERSHIP_INVARIANT_VIOLATION: 409,
  PERSIST_CONTAINER_CYCLE_DETECTED: 409,
  PERSIST_CONTAINER_DEPTH_EXCEEDED: 409,
  PERSIST_ENTITY_ID_RANGE_EXHAUSTED: 507,
  PERSIST_FENCING_TOKEN_STALE: 409,
  PERSIST_PARTITION_LEASE_HELD: 409,
  PERSIST_CHARACTER_UNAVAILABLE: 404,
  PERSIST_WORLD_LOAD_CORRUPTED: 500,
  PERSIST_UNSUPPORTED_SCHEMA_VERSION: 500,
  PERSIST_WORLD_NOT_READY: 503,
  PERSIST_ENTITY_TX_LOCKED: 409,
  PERSIST_TX_IDEMPOTENCY_MISMATCH: 409,
  PERSIST_CONSERVATION_VIOLATION: 409,
  PERSIST_TX_TIMEOUT: 504,
  PERSIST_TX_CONFLICT: 409,
  PERSIST_TX_UNAVAILABLE: 503,
  PERSIST_SERVICE_DEGRADED: 503,
  PERSIST_AUDIT_REASON_REQUIRED: 400,
  PERSIST_HANDOFF_FLUSH_FAILED: 503,
  PERSIST_FLUSH_COOLDOWN_ACTIVE: 429,
  PERSIST_PITR_WINDOW_UNAVAILABLE: 422,
  PERSIST_RESTORE_POINT_EXISTS: 409,
  PERSIST_ROLLBACK_PREVIEW_REQUIRED: 409,
  PERSIST_CHARACTER_ONLINE_BLOCKED: 409,
  PERSIST_RESTORE_DUPE_CONFLICT: 409,
  PERSIST_ROLLBACK_UNDO_EXPIRED: 410,
  PERSIST_RECONCILIATION_FAILED: 500,
} as const;
export type PersistErrorCode = keyof typeof PERSIST_ERRORS;

/** Ошибка слоя персистентности с кодом и деталями. */
export class PersistError extends Error {
  constructor(
    readonly code: PersistErrorCode,
    message: string = code,
    readonly details: Record<string, unknown> = {},
  ) {
    super(message);
    this.name = 'PersistError';
  }

  get status(): number {
    return PERSIST_ERRORS[this.code];
  }
}
